"""Published intrinsic effects that cannot test the reference (SI tab:stoj).

Stojkovic et al. (2012) report the ecDHFR I14 series only as intrinsic H/T and
D/T effects, obtained from observed effects by Northrop's method with exponent
3.34 (their SI, Materials and methods); the observed effects are not published.
Solving with an exponent puts the pair on that exponent's ray by construction,
so the offset they imply measures the rounding of the printed values and the
change of mass convention, not the chemistry.  This module tabulates that.

The values are in data/stojkovic2012_intrinsic.csv, transcribed from SI Tables
S1 and S2 (errors there are 95% confidence half-widths).  Until 2026-10-15 the
supplement's table and its summary numbers had no deposited code.

Run from analysis/:   python published_intrinsic.py
"""
from __future__ import annotations

import numpy as np
import pandas as pd

import masses as M

GSC = M.gamma_sc("C")
F0 = M.offset_F0("C")
G_SOURCE = 3.34          # the exponent the source solved Northrop's equation with


def offsets():
    d = pd.read_csv("../data/stojkovic2012_intrinsic.csv")
    d["F"] = np.log(d.x_HT) - GSC * np.log(d.x_DT)
    d["F_source"] = np.log(d.x_HT) - G_SOURCE * np.log(d.x_DT)
    return d


def summary(d=None):
    """Numbers the supplement quotes about the table."""
    d = offsets() if d is None else d
    big = float(d.F.abs().max())
    sd = float(d.F.std(ddof=1))
    # printed to two decimals: each effect can be off by 0.005, which moves the
    # offset at the source's exponent by at most this much
    rnd = 0.005 / d.x_HT + G_SOURCE * 0.005 / d.x_DT
    return dict(mean=float(d.F.mean()), max_abs=big, sd=sd,
                within_rounding=bool((d.F_source.abs() <= rnd).all()),
                max_abs_source=float(d.F_source.abs().max()),
                shift=float((d.F - d.F_source).mean()),
                ratio_max=abs(F0) / big, ratio_sd=abs(F0) / sd)


def table():
    """Body of tab:stoj, in the source's order."""
    d = offsets()
    lines = ["% Generated by analysis/published_intrinsic.py -- do not edit; edit the generator."]
    for _, r in d.iterrows():
        lines.append(f"{r.variant} & {r.T_C} & {r.x_HT:.2f} & {r.x_DT:.2f} & ${r.F:+.4f}$\\\\")
    # the closing rule travels with the body (LaTeX's \input is not expandable)
    return "\n".join(lines + ["\\bottomrule"]) + "\n"


def main():
    s = summary()
    print("Stojkovic et al. 2012, published intrinsic pairs (solved with exponent 3.34)")
    print(f"  offset at gamma_SC = {GSC:.5f}: mean {s['mean']:+.4f}, "
          f"max |F| {s['max_abs']:.4f}, s.d. {s['sd']:.4f}")
    print(f"  at the source's 3.34: max |F| {s['max_abs_source']:.4f} (rounding of "
          f"the printed values); convention shift {s['shift']:+.4f}")
    print(f"  every pair within its two-decimal rounding bound at 3.34: "
          f"{s['within_rounding']}")
    print(f"  |F0| = {abs(F0):.4f} is {s['ratio_max']:.1f} times the largest deviation "
          f"and {s['ratio_sd']:.1f} times their s.d.")
    with open("../results/sm_table_stoj.tex", "w") as f:
        f.write(table())
    print("[written] ../results/sm_table_stoj.tex")


if __name__ == "__main__":
    main()
