"""Data for the overview figure: two ratios, an unknown commitment, a half-line.

Panel B is the compatible set drawn as the range of a curve.  For each admissible
reciprocal commitment c > K_HT - 1 the base map K = x(1+c)/(x+c), inverted for
both isotope pairs with a shared reference, returns one intrinsic pair and hence
one intrinsic offset.  The horizontal axis is the masking fraction

    m = (K_HT - 1)/c,   0 (no masking, c -> infinity) to 1 (the singular limit),

which puts every observation on the same finite interval.  The compatible set is
the set of heights the curve reaches.  Both observations are the ones of the
geometry figure, so the two figures can be read together.

Panels A and C are schematics and carry no data.

Run from analysis/:   python export_fig_overview.py
"""
from __future__ import annotations

import sys

import numpy as np
from scipy.optimize import brentq

import masses as M
from corpus import series_record
from partial_id import F_min_exact

G = M.gamma_sc("C"); F0 = M.offset_F0("C")
OUT = "../figures/tikz/data/"

# the two observations of the geometry figure (export_fig_geom.CASES)
CASES = [("yadh", 7.13, 1.73), ("light", *series_record("light enzyme", 5.0))]
F_TOP = 0.62                      # plotted range; the curves continue to +infinity


def F_of_m(kht, kdt, m):
    """Intrinsic offset at masking fraction m, shared reference."""
    c = (kht - 1.0) / m
    xh = kht * c / (1.0 + c - kht)
    xd = kdt * c / (1.0 + c - kdt)
    return np.log(xh) - G * np.log(xd)


def main():
    bad = 0
    for name, kh, kd in CASES:
        Fobs = np.log(kh) - G * np.log(kd)
        Fmin, _, interior, _ = F_min_exact(kh, kd)
        # Theorem 1 territory or not, both observations sit on the open branch:
        # the curve starts at F_obs and only rises
        if interior or abs(Fmin - Fobs) > 1e-12:
            print(f"  FAIL overview: {name} is not on the open branch")
            bad += 1
        m = np.r_[0.0, np.geomspace(1e-4, 0.9999, 1500)]
        F = np.r_[Fobs, F_of_m(kh, kd, m[1:])]
        if np.any(np.diff(F) <= 0):
            print(f"  FAIL overview: F(m) is not increasing for {name}")
            bad += 1
        keep = F <= F_TOP
        # close the drawn curve exactly at the top of the plotted range
        mtop = brentq(lambda v: F_of_m(kh, kd, v) - F_TOP, m[keep][-1], 0.9999)
        with open(OUT + f"fo_mask_{name}.dat", "w") as f:
            f.write("m F\n")
            for u, v in zip(m[keep], F[keep]):
                f.write(f"{u:.6f} {v:.6f}\n")
            f.write(f"{mtop:.6f} {F_TOP:.6f}\n")
        with open(OUT + f"fo_obs_{name}.dat", "w") as f:
            f.write(f"m F\n0 {Fobs:.6f}\n")
        print(f"  {name:6s} F_obs {Fobs:+.4f}, curve rises monotonically to "
              f"+inf as m -> 1")

    # where the ecDHFR curve crosses the two thresholds
    kh, kd = CASES[1][1:]
    out = {}
    for lab, level in (("zero", 0.0), ("F0", F0)):
        mc = brentq(lambda v: F_of_m(kh, kd, v) - level, 1e-6, 0.9999)
        out[lab] = mc
        print(f"  ecDHFR reaches {lab:4s} at m = {mc:.4f}, c = {(kh - 1) / mc:.3f}")
    # the crossing of the reference must be the c = 4.037 of the geometry figure
    if abs((kh - 1) / out["zero"] - 4.037) > 5e-4:
        print("  FAIL overview: ecDHFR crossing disagrees with the geometry figure")
        bad += 1
    with open(OUT + "fo_cross.dat", "w") as f:
        f.write("m F\n")
        f.write(f"{out['F0']:.6f} {F0:.6f}\n{out['zero']:.6f} 0\n")
    with open(OUT + "fo_levels.tex", "w") as f:
        f.write("% Generated by analysis/export_fig_overview.py; do not edit.\n")
        f.write(f"\\def\\foFzero{{{F0:.6f}}}\n")
        f.write(f"\\def\\foFtop{{{F_TOP:.2f}}}\n")
        for name, kh, kd in CASES:          # the endpoints, for the set arrows
            f.write(f"\\def\\fo{name.capitalize()}F"
                    f"{{{np.log(kh) - G * np.log(kd):.6f}}}\n")
    print("overview figure data:", "OK" if not bad else f"{bad} FAILURES")
    return bad


if __name__ == "__main__":
    sys.exit(1 if main() else 0)
