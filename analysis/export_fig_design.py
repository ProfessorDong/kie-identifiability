"""Data for the design figure: what turns the yeast bound into a measured offset.

  A  The two nuisances act on one map.  For each bypass ratio phi_H, the
     largest binding offset F_bind at which the yeast endpoint still clears F0,
     worst case over the binding constants inside joint_nuisance.BIND_BOX
     (corners, which check_envelope_r verifies against the interior grid), at
     the two ends of the stipulated r range.  Drawn with the separate
     tolerances, the sampled line F_bind <= 0.164 - 1.465 phi and the point
     (phi, F_bind) = (0.080, 0.090) of the main text.
  B  Completion.  The intrinsic offset at known commitment c, with r solved
     jointly with c from the primary and secondary effects (completion.
     yadh_joint_r), and with a shared reference (r = 1).  Klinman's
     k_-1/k_cat = 1.3 to 7.3 maps to c in [15.4, 58.2].
  C  Pooling.  Nine variants that share the intrinsic pair (12, 2) and differ
     only in commitment, and the pair (3.75, 5/3) that reproduces all nine
     exactly (pooling_check.ladh_shared_pair_fit).  Every pair with the same
     u_H/u_D lies on one curve in the plane of log effects; the observations
     fix the curve, not the point on it.
  D  Error budget at known commitment c_H = m (K_HT - 1), r = 1.3107, the
     setting of the text: standard error of the completed offset from the
     published isotope errors alone, at rho = 0 and rho = -1, and the
     contribution of a commitment known to 10%.

Run from analysis/:   python export_fig_design.py      (about a minute)
"""
from __future__ import annotations

import sys

import numpy as np

import masses as M
import completion as C
import joint_nuisance as J
from pooling_check import ladh_shared_pair_fit

G = M.gamma_sc("C"); F0 = M.offset_F0("C")
OUT = "../figures/tikz/data/"
KH, KD, SH, SD = 7.13, 1.73, 0.07, 0.02          # Cha et al. 1989, average row
R_BUDGET = 1.3107                                 # as in the text's budget


def _write(name, header, rows, fmt="{:.6f}"):
    with open(OUT + name, "w") as f:
        f.write(header + "\n")
        for r in rows:
            f.write(" ".join(fmt.format(v) for v in r) + "\n")


# ------------------------------------------------------------------ panel A
def boundary(phi, r, lo=-0.12, hi=0.30, tol=5e-5):
    """Largest F_bind keeping the worst-case endpoint above F0 at bypass phi."""
    ok = lambda fb: J.worst_corner_endpoint(fb, phi, r) > F0
    if not ok(lo):
        return np.nan
    while hi - lo > tol:
        mid = 0.5 * (lo + hi)
        lo, hi = (mid, hi) if ok(mid) else (lo, mid)
    return 0.5 * (lo + hi)


def panel_A():
    bad = 0
    phis = np.round(np.arange(0.0, 0.2001, 0.01), 4)
    curves = {}
    for lab, r in (("rlo", J.R_RANGE[0]), ("rhi", J.R_RANGE[1])):
        fb = np.array([boundary(p, r) for p in phis])
        curves[lab] = fb
        _write(f"fd_joint_{lab}.dat", "phi fb",
               [(p, v) for p, v in zip(phis, fb) if np.isfinite(v)])
    # the sampled line must lie under both profiled boundaries wherever it is positive
    line = J.envelope_r(phis)
    pos = line > 0
    slack = np.min(np.minimum(curves["rlo"], curves["rhi"])[pos] - line[pos])
    if slack < -1e-4:
        print(f"  FAIL design A: the quoted line exceeds a profiled boundary by {-slack:.4f}")
        bad += 1
    # the larger r is the more demanding one
    if np.any(curves["rhi"] > curves["rlo"] + 1e-4):
        print("  FAIL design A: the boundary at the larger r is not the lower one")
        bad += 1
    # separate tolerances
    fb_tol, _ = J.marginal_tolerances()
    t_hi = float(C.bypass_tolerance(KH, KD, C.yadh_completion_joint(1.3)["r"], F0))
    t_lo = float(C.bypass_tolerance(KH, KD, C.yadh_completion_joint(7.3)["r"], F0))
    # the point of the text: inside both separate tolerances, outside the joint one
    pt = (0.080, 0.090)
    e_pt = J.endpoint(F_bind=pt[1], phi_H=pt[0])
    inside_sep = pt[0] < t_hi and pt[1] < fb_tol
    # and above the profiled boundary even at the most permissive r
    above = pt[1] > np.interp(pt[0], phis, curves["rlo"])
    if not (inside_sep and e_pt < F0 and above):
        print("  FAIL design A: the text's point is not inside the separate tolerances "
              "and below F0")
        bad += 1
    _write("fd_line.dat", "phi fb",
           [(p, J.envelope_r(p)) for p in (0.0, J.ENVELOPE_R_PHI_MAX)])
    with open(OUT + "fd_levels.tex", "w") as f:
        f.write("% Generated by analysis/export_fig_design.py; do not edit.\n")
        f.write(f"\\def\\fdFbTol{{{fb_tol:.6f}}}\n")
        f.write(f"\\def\\fdPhiTolLo{{{t_hi:.6f}}}\n\\def\\fdPhiTolHi{{{t_lo:.6f}}}\n")
        f.write(f"\\def\\fdPtPhi{{{pt[0]:.3f}}}\n\\def\\fdPtFb{{{pt[1]:.3f}}}\n")
    print(f"  A: binding tolerance {fb_tol:.4f}; bypass tolerance {100*t_hi:.1f}% to "
          f"{100*t_lo:.1f}%; point (0.080, 0.090) endpoint {e_pt:+.4f} < F0; "
          f"line slack {slack:.4f}")
    print("     boundary at phi = 0, 0.05, 0.10: r=1.31 " +
          ", ".join(f"{v:.4f}" for v in curves["rlo"][[0, 5, 10]]) +
          "; r=1.569 " + ", ".join(f"{v:.4f}" for v in curves["rhi"][[0, 5, 10]]))
    return bad, fb_tol, t_hi, t_lo


# ------------------------------------------------------------------ panel B
def panel_B():
    bad = 0
    a = np.geomspace(0.12, 3e4, 500)
    rows = []
    for v in a:
        j = C.yadh_completion_joint(v)
        rows.append((j["c"], j["F"], j["r"]))
    rows = np.array(rows)
    if np.any(np.diff(rows[:, 1]) >= 0):
        print("  FAIL design B: the completed offset is not decreasing in c")
        bad += 1
    _write("fd_comp_joint.dat", "c F r", [r for r in rows if r[1] <= 1.0])
    c1 = (KH - 1.0) * (1.0 + np.geomspace(1e-3, 1e4, 500))
    F1 = [C.yadh_completion((cc - (KH - 1)) / KH, r=1.0)["F"] for cc in c1]
    _write("fd_comp_r1.dat", "c F", [(u, v) for u, v in zip(c1, F1) if v <= 1.0])
    ends = [C.yadh_completion_joint(v) for v in (1.3, 7.3)]
    lo, hi = ends[1], ends[0]
    want = ("15.4", "58.2", "+0.209", "+0.534")
    got = (f"{hi['c']:.1f}", f"{lo['c']:.1f}", f"{lo['F']:+.3f}", f"{hi['F']:+.3f}")
    if got != want:
        print(f"  FAIL design B: completion ends {got}, text {want}")
        bad += 1
    Fobs = np.log(KH) - G * np.log(KD)
    with open(OUT + "fd_levels.tex", "a") as f:
        f.write(f"\\def\\fdCsing{{{KH - 1:.4f}}}\n")
        f.write(f"\\def\\fdClo{{{hi['c']:.4f}}}\n\\def\\fdChi{{{lo['c']:.4f}}}\n")
        f.write(f"\\def\\fdFlo{{{lo['F']:.5f}}}\n\\def\\fdFhi{{{hi['F']:.5f}}}\n")
        f.write(f"\\def\\fdFobs{{{Fobs:.5f}}}\n\\def\\fdFzero{{{F0:.6f}}}\n")
    print(f"  B: c in [{hi['c']:.1f}, {lo['c']:.1f}] gives F_int in "
          f"[{lo['F']:+.3f}, {hi['F']:+.3f}]; endpoint {Fobs:+.3f}; singular c {KH-1:.2f}")
    return bad


# ------------------------------------------------------------------ panel C
def panel_C():
    bad = 0
    f = ladh_shared_pair_fit()
    if f["witness_diff"] > 1e-12:
        print("  FAIL design C: the two pairs do not reproduce the same observations")
        bad += 1
    x0 = np.array([12.0, 2.0])
    u0 = 1 - 1 / x0
    cs = np.geomspace(0.15, 2.0, 9)                    # pooling_check witness
    s0 = cs / (1 + cs)
    K = 1 / (1 - np.outer(s0, u0))                     # z = u s
    lam = 0.8
    x1 = 1 / (1 - lam * u0)
    if np.max(np.abs(x1 - np.array(f["witness_x1"]))) > 1e-12:
        print("  FAIL design C: the second pair disagrees with pooling_check")
        bad += 1
    # the common curve, x_L(s) = 1/(1 - s u_L), s from 0 to 1/u_H (x_H -> inf)
    s = np.r_[np.linspace(0, s0.max(), 200), np.linspace(s0.max(), 0.999 / u0[0], 600)[1:]]
    xs = 1 / (1 - np.outer(s, u0))
    X = np.log(xs)
    keep = X[:, 0] <= 3.2                              # columns are (X_H, X_D)
    seen = s <= s0.max() + 1e-15
    _write("fd_pool_seen.dat", "xd xh", X[keep & seen][:, ::-1])
    _write("fd_pool_open.dat", "xd xh", X[keep & ~seen][:, ::-1])
    _write("fd_pool_obs.dat", "xd xh", np.log(K)[:, ::-1])
    _write("fd_pool_pairs.dat", "xd xh F",
           [(np.log(p[1]), np.log(p[0]), np.log(p[0]) - G * np.log(p[1])) for p in (x0, x1)])
    _write("fd_pool_ray.dat", "xd xh", [(0, 0), (0.95, 0.95 * G)])
    F_a, F_b = f["witness_F"]
    print(f"  C: pairs (12, 2) and ({x1[0]:.2f}, {x1[1]:.3f}) reproduce nine "
          f"observations to {f['witness_diff']:.0e}; offsets {F_a:+.3f}, {F_b:+.3f}")
    return bad


# ------------------------------------------------------------------ panel D
def panel_D():
    bad = 0
    m = np.geomspace(1.15, 30.0, 300)
    rows = []
    for v in m:
        c = v * (KH - 1)
        s0, s1 = C.isotope_error_budget(KH, KD, SH, SD, c, R_BUDGET)
        sc = 0.10 * abs(C.dF_dlnc(KH, KD, c, R_BUDGET))
        rows.append((v, s0, s1, sc))
    rows = np.array(rows)
    _write("fd_budget.dat", "m iso0 isom1 comm10", rows)
    b3 = C.isotope_error_budget(KH, KD, SH, SD, 3 * (KH - 1), R_BUDGET)
    if (f"{b3[0]:.3f}", f"{b3[1]:.3f}") != ("0.044", "0.057"):
        print(f"  FAIL design D: budget at m = 3 is {b3}, text 0.044 / 0.057")
        bad += 1
    if np.min(rows[:, 1]) <= abs(F0) / 2:
        print("  FAIL design D: the isotope floor falls below |F0|/2 somewhere")
        bad += 1
    # the 10% commitment curve meets the target between the text's m = 3 (5.3%)
    # and m = 5 (11.2%)
    need3 = C.commitment_precision_needed(KH, KD, 3 * (KH - 1), R_BUDGET)
    need5 = C.commitment_precision_needed(KH, KD, 5 * (KH - 1), R_BUDGET)
    if not need3 < 0.10 < need5:
        print("  FAIL design D: the 10% curve does not cross the target between m = 3 and 5")
        bad += 1
    _write("fd_budget_m3.dat", "m iso0 isom1", [(3.0, b3[0], b3[1])])
    with open(OUT + "fd_levels.tex", "a") as f:
        f.write(f"\\def\\fdTarget{{{abs(F0) / 2:.6f}}}\n")
    print(f"  D: at m = 3, {b3[0]:.3f} (rho 0) and {b3[1]:.3f} (rho -1); isotope floor "
          f"never below |F0|/2 = {abs(F0)/2:.3f}; commitment precision needed "
          f"{100*need3:.1f}% (m=3), {100*need5:.1f}% (m=5)")
    return bad


def main():
    bad, *_ = panel_A()
    bad += panel_B() + panel_C() + panel_D()
    print("design figure data:", "OK" if not bad else f"{bad} FAILURES")
    return bad


if __name__ == "__main__":
    sys.exit(1 if main() else 0)
