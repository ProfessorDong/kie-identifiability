"""Complete-benchmark longtable for the SI (Table `tab:full`).

Regenerates manuscript/sm_table_data.tex from the curated benchmark so the table
cannot drift from the data, which it previously did when new series were added.
"""
from __future__ import annotations

import pathlib

import numpy as np
import pandas as pd

import masses as M
from corpus import display_family

GSC = M.gamma_sc("C")
# Always results/.  A manuscript build copies the table from here; no
# manuscript directory is written by this script.
OUT = "../results/sm_table_data.tex"


def _dec(s: str) -> int:
    return len(s.split(".")[1]) if "." in s else 0


# Human thymidylate synthase: the source gives replicates, and the error here is
# the standard error of their mean, computed at full float precision.
COMPUTED_SE = {"10.1371/journal.pone.0196506"}


# The one printed pair whose value and error carry different decimal counts:
# Singh et al. 2014 SI, G121V-F125M at 35 C, D/T "1.80 +- 0.003".
AS_PRINTED = {(1.8, 0.003): "$1.80\\pm0.003$",
              (7.55, 0.03): "$7.550\\pm0.030$",
              (1.89, 0.009): "$1.89\\pm0.009$"}     # Islam et al. 2014, R166K, 25 C
# Pairs whose printed form depends on the record, not only on the value: Hong et
# al. 2006 print the W80M D/T effect at 40 C as "1.8 +- 0.02" and at 5 C as
# "1.80 +- 0.02", which are the same pair of floats.
AS_PRINTED_RECORD = {("10.1021/ja060196o", 40.0, "K_DT"): "$1.8\\pm0.02$"}


def _pair(v: float, e: float, computed: bool = False) -> str:
    """Value and error at the precision the source prints them.

    The CSV stores floats, which drop trailing zeros (2.00 -> 2, 0.10 -> 0.1).
    Every printed source gives a value and its error to the same number of
    decimals (Jonsson et al. "28.89 +- 1.10", Tsai and Klinman "13.0 +- 0.1"),
    so both are printed to the larger of the two decimal counts the stored
    numbers carry.  Until 2026-10-15 values were printed with %g and errors to
    two significant figures, which showed "13 +- 0.1", "2 +- 0.02" and
    "2.896 +- 0.13" for the published 13.0, 2.00 and 0.132.  Computed standard
    errors are rounded to two significant figures and the value is shown to at
    least that many decimals.  A check of every transcribed pair against the
    source text found one exception, kept as printed (AS_PRINTED), and a value
    whose value and error both end in zeros (Bahnson et al. "7.550 +- 0.030")
    cannot be recovered from floats, so it is listed there too.
    """
    if (v, e) in AS_PRINTED:
        return AS_PRINTED[(v, e)]
    if computed:
        es = f"{e:#.2g}".rstrip(".")
        nd = max(_dec(f"{v:g}"), _dec(es))
    else:
        nd = max(_dec(f"{v:g}"), _dec(f"{e:g}"))
        es = f"{e:.{nd}f}"
    return f"${v:.{nd}f}\\pm{es}$"


def _signed(x: float, nd: int) -> str:
    """A number in math mode, so a negative sign is a minus, not a hyphen."""
    return f"${x:+.{nd}f}$"


def main() -> None:
    d = pd.read_csv("../data/trinomial_benchmark.csv")
    lines, nrec = [], 0
    for (fam, var, step), g in d.groupby(["family", "variant", "step"], sort=False):
        # \\* forbids a page break after the group label, which otherwise strands
        # it at the foot of a page in the long benchmark table
        varx = var.replace("%", "\\%")       # solvent variants carry a percent sign
        varx = varx.replace("Mg2+", "Mg$^{2+}$")
        # a zero-width heading that runs across the empty cells, so a long variant
        # name does not widen column one; \multicolumn cannot open the first row,
        # which follows a non-expandable \input
        lines.append(f"\\rlap{{\\textit{{{display_family(fam, var)} {varx}, {step}}}}} & & & & & & \\\\*")
        for _, r in g.sort_values("T_C").iterrows():
            gam = np.log(r.K_HT) / np.log(r.K_DT)
            lh = (r.K_HT - 1.0) / (r.K_DT - 1.0)
            # the column is F_obs, NOT the identified-set endpoint: the two
            # differ wherever L_H < gamma_SC, which is most of the benchmark
            fobs = np.log(r.K_HT) - GSC * np.log(r.K_DT)
            # outside normal ordering (K_HT > K_DT > 1) the exponent and the
            # contrast are not defined as diagnostics; print dashes, not -78
            adm = r.K_HT > r.K_DT > 1.0
            gs, ls = (f"{gam:.3f}", f"{lh:.3f}") if adm else ("--", "--")
            cse = r.source_DOI in COMPUTED_SE
            ph = AS_PRINTED_RECORD.get((r.source_DOI, r.T_C, "K_HT")) or _pair(r.K_HT, r.K_HT_se, cse)
            pd_ = AS_PRINTED_RECORD.get((r.source_DOI, r.T_C, "K_DT")) or _pair(r.K_DT, r.K_DT_se, cse)
            lines.append(
                f" & ${r.T_C:g}$ & {ph}"
                f" & {pd_}"
                f" & {gs} & {ls} & {_signed(fobs, 4)}\\\\"
            )
            nrec += 1
    open(OUT, "w").write("% Generated by analysis/export_benchmark_table.py -- do not edit; edit the generator.\n" + "\n".join(lines) + "\n")
    nser = d.groupby(["family", "variant", "step"]).ngroups
    print(f"wrote {OUT}: {nrec} records in {nser} series")


if __name__ == "__main__":
    main()
