"""Index of the analysis scripts that the supplement names.

The supplement cites a script, or a function written module.function, beside
each number it computes.  script_index.csv says in one line what each such
script does and in which Supplementary Notes it is cited; this module turns
that file into the rows of the supplement's index table
(results/sm_table_scripts.tex) and provides the functions with which
audit_numbers.py keeps the index, the text and the code in step.

Run from analysis/:  python3 export_script_index.py
"""
import ast
import csv
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
INDEX = HERE / "script_index.csv"
OUT = HERE.parent / "results" / "sm_table_scripts.tex"
INDEX_LABEL = "sm:scripts"          # the section that holds the index itself
_NOT_CODE = {"py", "md", "csv", "tex", "txt", "dat", "cff", "zip", "pdf"}
PLACEHOLDER = "module.function"     # the generic form, as the supplement's opening page writes it


def rows():
    """The index as a list of (script, description, [note numbers])."""
    out = []
    with open(INDEX, newline="") as fh:
        for r in csv.DictReader(fh):
            notes = [int(n) for n in r["notes"].split(";") if n.strip()]
            out.append((r["script"], r["description"], notes))
    return out


def defined_names(script):
    """Names defined at the top level of a script: functions, classes, constants."""
    tree = ast.parse((HERE / script).read_text())
    names = {n.name for n in tree.body if isinstance(n, (ast.FunctionDef, ast.ClassDef))}
    for n in tree.body:
        if isinstance(n, ast.Assign):
            names |= {t.id for t in n.targets if isinstance(t, ast.Name)}
    return names


def named_in(tex):
    """Scripts and functions that a LaTeX text names in typewriter type.

    Returns (scripts, functions): the set of file names ending in .py, and the
    set of (script, function) pairs written module.function.
    """
    scripts, functions = set(), set()
    for raw in re.findall(r"\\texttt\{([^}]*)\}", tex):
        name = raw.replace("\\_", "_")
        if name == PLACEHOLDER:
            continue
        if re.fullmatch(r"[A-Za-z0-9_]+\.py", name):
            scripts.add(name)
        elif re.fullmatch(r"[a-z0-9_]+\.[A-Za-z0-9_]+", name) and name.rsplit(".", 1)[1] not in _NOT_CODE:
            module, function = name.split(".")
            functions.add((module + ".py", function))
    return scripts, functions


def notes_citing(body):
    """For the body of the supplement, the Supplementary Notes that cite each
    script: {script: sorted note numbers}.  A Note is a \\section, numbered in
    order; the section that holds the index itself is not counted."""
    starts = [m.start() for m in re.finditer(r"^\\section\{", body, re.M)]
    cited = {}
    for k, start in enumerate(starts):
        end = starts[k + 1] if k + 1 < len(starts) else len(body)
        chunk = body[start:end]
        if "\\label{" + INDEX_LABEL + "}" in chunk[:400]:
            continue
        scripts, functions = named_in(chunk)
        for script in scripts | {s for s, _ in functions}:
            cited.setdefault(script, set()).add(k + 1)
    return {s: sorted(v) for s, v in cited.items()}


def _tex(text):
    for a, b in (("\\", "\\textbackslash{}"), ("_", "\\_"), ("%", "\\%"), ("&", "\\&"), ("#", "\\#")):
        text = text.replace(a, b)
    text = re.sub(r"(?<=\s)-(\d+)", r"$-\1$", text)          # a negative number in running text
    return re.sub(r'"([^"]*)"', r"\\texttt{\1}", text)


def table():
    """Rows of the supplement's index table."""
    lines = ["% Generated by analysis/export_script_index.py from script_index.csv -- do not edit; edit the generator."]
    for script, description, notes in rows():
        where = ", ".join(str(n) for n in notes) if notes else "all"
        lines.append(f"\\texttt{{{script.replace('_', chr(92) + '_')}}} & {_tex(description)} & {where}\\\\")
    return "\n".join(lines) + "\n"


def main():
    missing = [s for s, _, _ in rows() if not (HERE / s).is_file()]
    if missing:
        raise SystemExit(f"script_index.csv lists scripts that do not exist: {missing}")
    OUT.write_text(table())
    print(f"[written] {OUT.relative_to(HERE.parent)}: {len(rows())} scripts")


if __name__ == "__main__":
    main()
