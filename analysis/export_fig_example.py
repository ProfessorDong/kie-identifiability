"""Data for the worked-example figure: one measured pair, every commitment.

For the minimal competitive scheme, Northrop's expression for an observed
tritium-referenced V/K isotope effect is

    K = x (1 + C_T) / (1 + x C_T),      C_T = k_T / k_off,

with x the intrinsic effect and C_T the forward commitment of the tritiated
substrate (the reciprocal commitment of the other scripts is c = 1/C_T).
Solving for the intrinsic effect at an assumed commitment gives

    x = K / (1 - (K - 1) C_T),          0 <= C_T < 1/(K_HT - 1).

The figure plots the intrinsic Swain-Schaad exponent ln x_H / ln x_D implied by
a measured pair against the assumed commitment, written as the fraction
m = C_T (K_HT - 1) of the largest commitment the data allow.  Two published
pairs are drawn: one observed above the semiclassical reference exponent and
one observed below it.  worked_table() returns the rows the text tabulates.

Run from analysis/:   python export_fig_example.py
"""
from __future__ import annotations

import sys

import numpy as np
from scipy.optimize import brentq

import masses as M
from corpus import series_record

G = M.gamma_sc("C")
OUT = "../figures/tikz/data/"

# the two observations of the geometry figure
CASES = [("yadh", 7.13, 1.73), ("light", *series_record("light enzyme", 5.0))]
E_TOP = 5.0                       # plotted range; the curves continue to +infinity
TABLE_C = {"yadh": (0.0, 0.05, 0.10, 0.15), "light": (0.0, 0.10, 0.20, 0.30)}


def intrinsic(K, C):
    """Intrinsic effect behind an observed effect K at forward commitment C_T."""
    return K / (1.0 - (K - 1.0) * C)


def exponent(kht, kdt, C):
    """Intrinsic Swain-Schaad exponent implied by the pair at commitment C_T."""
    return np.log(intrinsic(kht, C)) / np.log(intrinsic(kdt, C))


def c_max(kht):
    """Largest forward commitment the H/T effect allows (not attained)."""
    return 1.0 / (kht - 1.0)


def crossing(kht, kdt):
    """Commitment C_T at which the implied exponent equals the reference."""
    return brentq(lambda C: exponent(kht, kdt, C) - G, 1e-9, c_max(kht) * (1 - 1e-9))


def worked_table():
    """Rows (case, C_T, x_H, x_D, exponent) tabulated in the text."""
    rows = []
    for name, kh, kd in CASES:
        for C in TABLE_C[name]:
            rows.append((name, C, intrinsic(kh, C), intrinsic(kd, C), exponent(kh, kd, C)))
    return rows


def main():
    bad = 0
    for name, kh, kd in CASES:
        m = np.r_[0.0, np.geomspace(1e-4, 0.9999, 2000)]
        C = m * c_max(kh)
        e = exponent(kh, kd, C)
        if np.any(np.diff(e) <= 0):
            print(f"  FAIL example: the implied exponent is not increasing for {name}")
            bad += 1
        keep = e <= E_TOP
        mtop = brentq(lambda v: exponent(kh, kd, v * c_max(kh)) - E_TOP, m[keep][-1], 0.9999)
        with open(OUT + f"fx_exp_{name}.dat", "w") as f:
            f.write("m e\n")
            for u, v in zip(m[keep], e[keep]):
                f.write(f"{u:.6f} {v:.6f}\n")
            f.write(f"{mtop:.6f} {E_TOP:.6f}\n")
        with open(OUT + f"fx_obs_{name}.dat", "w") as f:
            f.write(f"m e\n0 {e[0]:.6f}\n")
        print(f"  {name:6s} observed exponent {e[0]:.3f}, largest commitment "
              f"C_T < {c_max(kh):.3f}, implied exponent rises to +inf")

    # the pair observed above the reference must stay above it; the pair
    # observed below must cross it, at the commitment of the geometry figure
    kh, kd = CASES[0][1:]
    if exponent(kh, kd, 0.0) <= G:
        print("  FAIL example: the yeast pair is not above the reference")
        bad += 1
    kh, kd = CASES[1][1:]
    Cx = crossing(kh, kd)
    print(f"  ecDHFR crosses the reference at C_T = {Cx:.3f} (c = {1 / Cx:.3f}), "
          f"m = {Cx / c_max(kh):.4f}; intrinsic H/T there {intrinsic(kh, Cx):.2f}")
    if abs(1.0 / Cx - 4.037) > 5e-4:
        print("  FAIL example: ecDHFR crossing disagrees with the geometry figure")
        bad += 1
    with open(OUT + "fx_cross.dat", "w") as f:
        f.write(f"m e\n{Cx / c_max(kh):.6f} {G:.6f}\n")
    with open(OUT + "fx_levels.tex", "w") as f:
        f.write("% Generated by analysis/export_fig_example.py; do not edit.\n")
        f.write(f"\\def\\fxGamma{{{G:.6f}}}\n")
        f.write(f"\\def\\fxTop{{{E_TOP:.2f}}}\n")
        for name, kh, kd in CASES:
            f.write(f"\\def\\fx{name.capitalize()}E{{{exponent(kh, kd, 0.0):.6f}}}\n")
    for name, C, xh, xd, e in worked_table():
        print(f"  table {name:6s} C_T {C:.2f}: x_H {xh:6.2f}  x_D {xd:.2f}  exponent {e:.2f}")
    print("worked-example figure data:", "OK" if not bad else f"{bad} FAILURES")
    return bad


if __name__ == "__main__":
    sys.exit(1 if main() else 0)
